
#!/usr/bin/env python3
"""Replace four legacy hyphenation sources with pinned hyph-utf8 files.

Run from the repository root:

    python3 tools/replace_legacy_hyphen_sources.py

Requires Python 3 and Git. Does not modify README or license notices.
"""

from pathlib import Path
import hashlib
import re
import subprocess
import sys
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "hyphen-sources"
GEN = ROOT / "tools" / "gen_hyphen.py"
OUT = ROOT / "niori-pdf-hyphen-data.el"
LOCK = SRC / "SOURCES.lock"

UPSTREAM = "https://github.com/hyphenation/tex-hyphen.git"
RAW_BASE = (
    "https://raw.githubusercontent.com/hyphenation/tex-hyphen/"
    "{revision}/hyph-utf8/tex/generic/hyph-utf8/"
    "patterns/tex/{filename}"
)

REPLACEMENTS = {
    "american": ("ushyph.txt", "hyph-en-us.tex"),
    "german": ("dehyphn.txt", "hyph-de-1996.tex"),
    "french": ("frhyph.txt", "hyph-fr.tex"),
    "british": ("gbhyph.txt", "hyph-en-gb.tex"),
}

OLD_CREDITS = {
    "american": ";;   american   Frank M. Liang's classic TeX set (via cl-typesetting)",
    "german": ";;   german     classic 'dehyphn' set, 1996 orthography (via cl-typesetting)",
    "french": ";;   french     classic French set, Seroul/Gaulle (via cl-typesetting)",
    "british": ";;   british    classic British set, Abbott/Wujastyk (via cl-typesetting)",
}


def upstream_revision():
    result = subprocess.check_output(
        ["git", "ls-remote", UPSTREAM, "HEAD"],
        text=True,
    )
    if not result.strip():
        raise RuntimeError("Could not resolve upstream HEAD")
    return result.split()[0]


def download(filename, revision):
    url = RAW_BASE.format(revision=revision, filename=filename)
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "niori-pdf-hyphen-source-migration"},
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def inspect_source(data, filename):
    """Validate UTF-8 TeX source and extract its declared minima."""
    text = data.decode("utf-8-sig")

    if not re.search(r"\\patterns\s*\{", text):
        raise RuntimeError(f"{filename}: missing patterns block")

    header = text.split(r"\patterns", 1)[0]

    def minimum(name):
        match = re.search(
            rf"(?m)^%\s*{name}:\s*(\d+)\s*$",
            header,
        )
        if not match:
            raise RuntimeError(
                f"{filename}: missing hyphenmins {name} metadata"
            )
        return int(match.group(1))

    return text, minimum("left"), minimum("right")


def update_generator(original, revision, metadata):
    text = original

    for language, (old_file, new_file) in REPLACEMENTS.items():
        left, right = metadata[language]

        # Match the complete dict(...) expression, including its
        # closing parenthesis on the final metadata line.
        pattern = re.compile(
            rf'(?ms)^    "{re.escape(language)}": dict\(\n'
            rf'.*?^\s+license=.*?\),'
        )

        match = pattern.search(text)
        if not match:
            raise RuntimeError(
                f"Could not locate LANGS entry for {language}"
            )

        replacement = f'''    "{language}": dict(
        file="{new_file}", parser="hyph-utf8",
        left={left}, right={right},
        origin="hyph-utf8 {new_file} (upstream revision {revision})",
        authors="See source file header",
        license="See source file header",
        url="https://github.com/hyphenation/tex-hyphen"),'''

        text = text[:match.start()] + replacement + text[match.end():]

    # Replace the four old static credits in build_header().
    for language, (old_file, new_file) in REPLACEMENTS.items():
        old_credit = re.compile(
            r'^\s*";;\s*' + re.escape(language)
            + r'\s+[^"]*",\n',
            re.M,
        )

        new_credit = (
            f'        ";;   {language:<10} {new_file} '
            '(see upstream source header)",\n'
        )

        text, count = old_credit.subn(new_credit, text)

        if count != 1:
            raise RuntimeError(
                f"Could not update header credit for {language}; "
                f"found {count}"
            )

    return text

def write_lock(revision, downloads):
    lines = [
        "# Generated by replace_legacy_hyphen_sources.py",
        f"repository {UPSTREAM}",
        f"revision {revision}",
        "",
    ]

    for filename, data in sorted(downloads.items()):
        digest = hashlib.sha256(data).hexdigest()
        lines.append(f"{digest}  {filename}")

    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    if not SRC.is_dir() or not GEN.is_file() or not OUT.is_file():
        sys.exit("Run this script from a complete niori-pdf checkout.")

    print("Resolving upstream revision...")
    revision = upstream_revision()
    print(f"Upstream revision: {revision}")

    # Verify the original files and target paths before downloading.
    for old_file, new_file in REPLACEMENTS.values():
        if not (SRC / old_file).is_file():
            raise RuntimeError(f"Missing legacy source: {old_file}")
        if (SRC / new_file).exists():
            raise RuntimeError(f"Target already exists: {new_file}")

    # Download and validate everything before modifying anything.
    downloads = {}
    metadata = {}

    for language, (old_file, new_file) in REPLACEMENTS.items():
        print(f"Downloading {new_file}...")
        data = download(new_file, revision)
        text, left, right = inspect_source(data, new_file)

        downloads[new_file] = data
        metadata[language] = (left, right)

        print(
            f"  {language}: {len(data)} bytes, "
            f"left={left}, right={right}"
        )

    original_gen = GEN.read_bytes()
    original_out = OUT.read_bytes()
    original_lock = LOCK.read_bytes() if LOCK.exists() else None

    original_sources = {
        old_file: (SRC / old_file).read_bytes()
        for old_file, new_file in REPLACEMENTS.values()
    }

    updated_gen = update_generator(
        original_gen.decode("utf-8"),
        revision,
        metadata,
    )

    try:
        print("\nInstalling source files...")
        for filename, data in downloads.items():
            (SRC / filename).write_bytes(data)

        print("Updating generator...")
        GEN.write_text(updated_gen, encoding="utf-8")

        print("Testing all four sources with the existing parser...")
        for language in REPLACEMENTS:
            subprocess.run(
                [sys.executable, str(GEN), "--lang", language],
                cwd=ROOT,
                stdout=subprocess.DEVNULL,
                check=True,
            )
            print(f"  {language}: OK")

        print("Removing legacy source files...")
        for old_file, new_file in REPLACEMENTS.values():
            (SRC / old_file).unlink()

        print("Regenerating complete hyphenation database...")
        subprocess.run(
            [sys.executable, str(GEN)],
            cwd=ROOT,
            check=True,
        )

        print("Writing pinned source manifest...")
        write_lock(revision, downloads)

    except Exception:
        print("\nMigration failed; restoring original files...")

        GEN.write_bytes(original_gen)
        OUT.write_bytes(original_out)

        for filename, data in original_sources.items():
            (SRC / filename).write_bytes(data)

        for old_file, new_file in REPLACEMENTS.values():
            target = SRC / new_file
            if target.exists():
                target.unlink()

        if original_lock is None:
            if LOCK.exists():
                LOCK.unlink()
        else:
            LOCK.write_bytes(original_lock)

        raise

    print("\nMigration completed successfully.")
    print(f"Pinned upstream revision: {revision}")
    print(f"Source manifest: {LOCK}")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        sys.exit(f"ERROR: {exc}")

